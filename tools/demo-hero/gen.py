#!/usr/bin/env python3
"""Build demo-hero.html: unlisted preview, Owner 22 Nov ("show me different stuff apart from this
chart, what else can we add instead of this, to make our website hero section look jaw dropping").

The page IS the live homepage (index.html: header, headline, buttons, everything below), with ONLY
the hero chart (the .hv-art-wrap canvas) swapped for a stage that shows one of five variants
(assets/demo-hero.js), plus a sticky A-E switcher. noindex,nofollow; NOT in the nav, sitemap or
tools/og/pages.json. index.html is not touched. Run from the repo root:  python3 tools/demo-hero/gen.py
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'index.html')
OUT = os.path.join(ROOT, 'demo-hero.html')

page = open(SRC, encoding='utf-8').read()
build = json.load(open(os.path.join(ROOT, 'assets', 'version.json')))['build']

# ---------------------------------------------------------------- head: unlisted, no share/SEO tags
head, rest = page.split('</head>', 1)
head = re.sub(r'<meta (property|name)="(og|twitter):[^\n]*\n', '', head)
head = re.sub(r'<meta name="description"[^>]*>\n', '', head)
head = re.sub(r'<link rel="canonical"[^>]*>\n', '', head)
head = re.sub(r'<link rel="preload" as="image"[^>]*>\n', '', head)
head = re.sub(r'<script type="application/ld\+json">.*?</script>\n?', '', head, flags=re.S)
head = re.sub(r'<title>.*?</title>', '<title>TradeZoro · Hero visual variations (demo)</title>', head)
head = head.replace('<meta name="viewport" content="width=device-width, initial-scale=1.0">',
                    '<meta name="viewport" content="width=device-width, initial-scale=1.0">\n'
                    '<!-- DEMO PAGE (Owner 22 Nov). The homepage with five hero-visual variations. Unlisted: noindex,\n'
                    '     not in nav, sitemap or tools/og/pages.json. GENERATED by tools/demo-hero/gen.py from\n'
                    '     index.html; edit that script, not this file. -->\n'
                    '<meta name="robots" content="noindex,nofollow">\n'
                    '<meta name="description" content="Five previews of the TradeZoro homepage hero visual. Education only. Not financial advice.">')
css = '<link rel="stylesheet" href="assets/home-v2.css?v=%s">' % build
assert css in head, 'index.html stylesheet line changed; update gen.py'
head = head.replace(css, css + '\n<link rel="stylesheet" href="assets/demo-hero.css?v=%s">' % build)
assert 'noindex' in head and 'og:' not in head

# ---------------------------------------------------------------- body: swap only the hero chart
art = re.search(r'<div class="hv-art-wrap" data-hv-art>.*?</div>\n', rest)
assert art, 'index.html hero canvas markup changed; update gen.py'
stage = '''<div class="dh-stage" data-dh-stage>
<div class="dh-v dh-a" data-v="A" hidden><canvas class="dh-cv dh-mask" aria-hidden="true"></canvas><span class="hv-ex">Recorded order book · BTC/USD</span></div>
<div class="dh-v dh-b" data-v="B" hidden><div class="dh-b-g" data-dh-b></div></div>
<div class="dh-v dh-c" data-v="C" hidden><canvas class="dh-cv" aria-hidden="true"></canvas><ul class="dh-sess" data-dh-sess aria-label="Market sessions now"></ul><div class="dh-tiles" data-dh-tiles aria-label="Last prices"></div></div>
<div class="dh-v dh-d" data-v="D" hidden><canvas class="dh-cv dh-mask" aria-hidden="true"></canvas><span class="hv-ex">Recorded NQ minute · footprint</span></div>
<div class="dh-v dh-e" data-v="E" hidden><div class="dh-cards" data-dh-cards></div><div class="dh-dock" data-dh-dock role="group" aria-label="Products"></div></div>
</div>
'''
rest = rest[:art.start()] + stage + rest[art.end():]
rest = rest.replace('<body class="cm-page hv-page">', '<body class="cm-page hv-page dh-page">', 1)
assert 'dh-page' in rest

switcher = '''<nav class="dh-sw" data-dh-sw aria-label="Hero variations">
<p class="dh-idea" data-dh-idea aria-live="polite"></p>
<div class="dh-seg" role="group" aria-label="Pick a variation">
<button type="button" data-k="A"><b>A</b><span>Liquidity</span></button><button type="button" data-k="B"><b>B</b><span>Command centre</span></button><button type="button" data-k="C"><b>C</b><span>Globe</span></button><button type="button" data-k="D"><b>D</b><span>Order flow</span></button><button type="button" data-k="E"><b>E</b><span>Dock</span></button>
</div>
</nav>
'''
assert rest.count('</main>') == 1
rest = rest.replace('</main>', '</main>\n' + switcher, 1)
hv = '<script src="assets/home-v2.js?v=%s" defer></script>' % build
assert hv in rest
rest = rest.replace(hv, hv + '\n<script src="assets/world-map-path.js?v=%s" defer></script>\n'
                    '<script src="assets/demo-hero.js?v=%s" defer></script>' % (build, build))

out = head + '</head>' + rest
open(OUT, 'w', encoding='utf-8').write(out)
print('wrote', os.path.relpath(OUT, ROOT), len(out), 'bytes')
