#!/usr/bin/env node
// Writes functions/connect/finatic/_ver.js: VER = sha256 of every source file the tz-finatic-edge Worker bundles (relative imports
// followed from workers/finatic-edge/src/index.js) plus its wrangler.jsonc. Run by BOTH deploy-site.yml and deploy-finatic-edge.yml
// before they bundle, so the Pages build and the Worker each carry the hash of the order code they run. Pages forwards a broker call
// to the Worker only when the hashes match (_fin.js pagesEntry): a Worker left on older order code (bug 23 Nov: the 19 Nov Worker
// was still answering the Owner's orders) is never used, the call runs on Pages with the current code.
// --check: exit 1 if the committed _ver.js is not 'dev' (it must stay 'dev' in git; CI writes the real value).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'functions/connect/finatic/_ver.js');
export function edgeFiles() {
  const seen = new Set(), todo = [path.join(ROOT, 'workers/finatic-edge/src/index.js')];
  while (todo.length) {
    const f = todo.pop(); if (seen.has(f)) continue; seen.add(f);
    const src = fs.readFileSync(f, 'utf8');
    for (const m of src.matchAll(/(?:^|[\s;])(?:import|export)\b[^'"]*?\bfrom\s*['"](\.{1,2}\/[^'"]+)['"]/gm)) todo.push(path.resolve(path.dirname(f), m[1]));
  }
  return [...seen].filter((f) => f !== OUT).map((f) => path.relative(ROOT, f)).sort().concat('workers/finatic-edge/wrangler.jsonc');
}
export function edgeHash() {
  const h = crypto.createHash('sha256');
  for (const f of edgeFiles()) { h.update(f + '\0'); h.update(fs.readFileSync(path.join(ROOT, f))); h.update('\0'); }
  return h.digest('hex').slice(0, 16);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const ok = /VER = 'dev'/.test(fs.readFileSync(OUT, 'utf8'));
    if (!ok) { console.error('functions/connect/finatic/_ver.js must stay VER = \'dev\' in git (CI writes the real hash)'); process.exit(1); }
    process.exit(0);
  }
  const files = edgeFiles(), v = edgeHash();
  if (files.length < 5 || !files.includes('functions/connect/finatic/order.js')) { console.error('edge file list looks wrong: ' + files.join(',')); process.exit(1); }
  fs.writeFileSync(OUT, "// GENERATED by tools/gen-edge-ver.mjs at deploy time. In git it stays 'dev'.\nexport const VER = '" + v + "';\n");
  console.log('edge code version ' + v + ' (' + files.length + ' files)');
}
